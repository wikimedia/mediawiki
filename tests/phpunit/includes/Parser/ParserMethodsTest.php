	): void {
		$this->enableAutoCreateTempUser( [ 'matchPattern' => '~2$1' ] );
		$this->overrideConfigValue( MainConfigNames::LanguageCode, 'qqx' );

		$parser = $this->getServiceContainer()->getParser();
