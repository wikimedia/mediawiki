<?php

namespace Wikimedia\Rdbms\DBAL;

use Doctrine\DBAL\Platforms\PostgreSQLPlatform;
use Doctrine\DBAL\Schema\TableDiff;
use LogicException;
use Wikimedia\Timestamp\ConvertibleTimestamp;
use Wikimedia\Timestamp\TimestampFormat as TS;

class MWPostgreSqlPlatform extends PostgreSQLPlatform {
	/**
	 * Handles Postgres unique timestamp format
	 * @inheritDoc
	 *
	 * @param mixed[] $column The column definition array.
	 * @return string Postgres specific SQL code portion needed to set a default value.
	 */
	public function getDefaultValueDeclarationSQL( array $column ): string {
		$type = $this->getColumnTypeOrNull( $column );
		$default = $column['default'] ?? null;

		if ( $type instanceof TimestampType && $default ) {
			if ( isset( $column['allowInfinite'] ) &&
				$column['allowInfinite'] &&
				$default === 'infinity'
			) {
				$pgTimestamp = $default;
			} else {
				$timestamp = new ConvertibleTimestamp( $default );
				$pgTimestamp = $timestamp->getTimestamp( TS::POSTGRES );
			}

			return " DEFAULT '$pgTimestamp' ";
		}

		return parent::getDefaultValueDeclarationSQL( $column );
	}

	/**
	 * @inheritDoc
	 * @phpcs:disable PSR2.Methods.MethodDeclaration.Underscore
	 */
	protected function _getCreateTableSQL( string $name, array $columns, array $options = [] ): array {
		// phpcs:enable
		$tableSql = parent::_getCreateTableSQL( $name, $columns, $options );
		foreach ( $columns as $column ) {
			$type = $this->getColumnType( $column );
			if ( $type instanceof EnumType && $column['fixed'] ) {
				// PostgreSQL does support ENUM datatype but they need to be
				// created severally with CREATE TYPE command for each column
				// as it's not possible to feed the values directly in the
				// column declaration as it could be done in MySQL.
				$typeSql = $type->makeEnumTypeSql( $column, $this );
				array_unshift( $tableSql, $typeSql );
			}
		}

		return $tableSql;
	}

	/**
	 * Keep using SERIAL for autoincrement columns, like DBAL 3 did.
	 *
	 * DBAL 4 uses identity columns instead (GENERATED BY DEFAULT AS IDENTITY).
	 * Existing installations have SERIAL columns, and DatabasePostgres relies
	 * on the column default being nextval() (e.g. getInsertIdColumnForUpsert()
	 * and duplicateTableStructure()), so switching would need a migration.
	 *
	 * @see https://github.com/doctrine/dbal/pull/5396
	 * @inheritDoc
	 */
	public function getIntegerTypeDeclarationSQL( array $column ): string {
		return empty( $column['autoincrement'] ) ? 'INT' : 'SERIAL';
	}

	/**
	 * @see getIntegerTypeDeclarationSQL()
	 * @inheritDoc
	 */
	public function getBigIntTypeDeclarationSQL( array $column ): string {
		return empty( $column['autoincrement'] ) ? 'BIGINT' : 'BIGSERIAL';
	}

	/**
	 * @see getIntegerTypeDeclarationSQL()
	 * @inheritDoc
	 */
	public function getSmallIntTypeDeclarationSQL( array $column ): string {
		return empty( $column['autoincrement'] ) ? 'SMALLINT' : 'SMALLSERIAL';
	}

	/**
	 * Add or drop autoincrement using a sequence default, like DBAL 3 did,
	 * instead of DBAL 4's ADD GENERATED BY DEFAULT AS IDENTITY / DROP IDENTITY.
	 *
	 * @see getIntegerTypeDeclarationSQL()
	 * @inheritDoc
	 */
	public function getAlterTableSQL( TableDiff $diff ): array {
		$sql = parent::getAlterTableSQL( $diff );

		$table = $diff->getOldTable();
		$tableNameSQL = $table->getQuotedName( $this );
		foreach ( $diff->getChangedColumns() as $columnDiff ) {
			if ( !$columnDiff->hasAutoIncrementChanged() ) {
				continue;
			}
			$newColumn = $columnDiff->getNewColumn();
			$columnNameSQL = $newColumn->getQuotedName( $this );
			$alterColumnSql = "ALTER TABLE $tableNameSQL ALTER $columnNameSQL";

			if ( $newColumn->getAutoincrement() ) {
				$identitySql = "$alterColumnSql ADD GENERATED BY DEFAULT AS IDENTITY";
				$seqName = $table->getName() . '_' . $columnNameSQL . '_seq';
				$replacement = [
					"CREATE SEQUENCE $seqName",
					"SELECT setval('$seqName', (SELECT MAX($columnNameSQL) FROM $tableNameSQL))",
					"$alterColumnSql SET DEFAULT nextval('$seqName')",
				];
			} else {
				$identitySql = "$alterColumnSql DROP IDENTITY";
				// Do not drop the sequence, like DBAL 3
				$replacement = [ "$alterColumnSql DROP DEFAULT" ];
			}

			$pos = array_search( $identitySql, $sql, true );
			if ( $pos === false ) {
				throw new LogicException( "Expected '$identitySql' in the SQL generated by DBAL" );
			}
			array_splice( $sql, $pos, 1, $replacement );
		}

		return $sql;
	}

	/**
	 * @inheritDoc
	 */
	public function getBlobTypeDeclarationSQL( array $column ): string {
		// MySQL goes with varbinary for collation reasons, but postgres can't
		// properly understand BYTEA type and works just fine with TEXT type
		// FIXME: This should be fixed at some point (T257755)
		return 'TEXT';
	}

	/**
	 * @inheritDoc
	 */
	public function getBinaryTypeDeclarationSQL( array $column ): string {
		// MySQL goes with varbinary for collation reasons, but postgres can't
		// properly understand BYTEA type and works just fine with TEXT type
		// FIXME: This should be fixed at some point (T257755)
		return 'TEXT';
	}

	/**
	 * @inheritDoc
	 */
	public function getFloatDeclarationSQL( array $column ): string {
		return 'FLOAT';
	}

	/**
	 * @inheritDoc
	 */
	public function getDateTimeTzTypeDeclarationSQL( array $column ): string {
		return 'TIMESTAMPTZ';
	}
}
